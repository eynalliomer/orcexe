"""Private publication receipts and preservation of human-owned text."""

import hashlib
import json
import os
from pathlib import Path
import re

from orcexe import fsio

RECEIPT = '.publish-receipt.json'
HUMAN = re.compile(r'<!-- orcexe:human -->.*?<!-- /orcexe:human -->', re.S)
HUMAN_OPEN = '<!-- orcexe:human -->'
HUMAN_CLOSE = '<!-- /orcexe:human -->'


def human_parts(content):
    """Return outside text and exact blocks; malformed tails are human-owned."""
    first = content.find(HUMAN_OPEN)
    if first < 0:
        return content, []
    outside, blocks, cursor = [], [], 0
    while True:
        start = content.find(HUMAN_OPEN, cursor)
        if start < 0:
            outside.append(content[cursor:])
            return ''.join(outside), blocks
        end = content.find(HUMAN_CLOSE, start + len(HUMAN_OPEN))
        nested = content.find(HUMAN_OPEN, start + len(HUMAN_OPEN))
        if end < 0 or 0 <= nested < end:
            # Even earlier well-formed blocks belong to this single saved tail.
            return content[:first], [content[first:]]
        end += len(HUMAN_CLOSE)
        outside.append(content[cursor:start])
        blocks.append(content[start:end])
        cursor = end


def digest(text):
    return hashlib.sha256(text.encode('utf-8') if isinstance(text, str) else text).hexdigest()


def check(directory, name):
    directory = Path(directory)
    if directory.is_symlink():
        raise ValueError('output_symlink')
    path = directory / name
    if path.is_symlink():
        if os.readlink(path) != '.map-current/' + name:
            raise ValueError('output_symlink')
        pointer = directory / '.map-current'
        if not pointer.is_symlink():
            raise ValueError('output_symlink')
        target = os.readlink(pointer)
        if not re.fullmatch(r'\.map-generation-[A-Za-z0-9_-]+', target):
            raise ValueError('output_symlink')
        if (directory / target).is_symlink() or (directory / target / name).is_symlink():
            raise ValueError('output_symlink')
    return path


def text(path):
    """Keep CRLF and the human block's exact UTF-8 bytes."""
    return Path(path).read_bytes().decode('utf-8')


def contents(path):
    raw = Path(path).read_bytes()
    try:
        return raw.decode('utf-8')
    except UnicodeError:
        return raw


def record(content):
    result = dict(sha256=digest(content))
    if isinstance(content, str):
        result['text'] = content
    return result


def read(directory):
    path = check(directory, RECEIPT)
    try:
        value = fsio.read_json(path)
        if value.get('schema') != 'orcexe.publication.v1' or not isinstance(value['files'], dict):
            raise ValueError('publication_receipt_invalid')
        return value
    except FileNotFoundError:
        return dict(schema='orcexe.publication.v1', files={})


def prepare(directory, outputs, receipt=None, public_directory=None):
    """Return a transaction's bytes and paths whose human edits were kept.

    Current-state is always regenerated, carrying all human blocks to the end.
    Outside edits receive a one-time previous snapshot instead of a proposal.
    Other text edits keep the entire original and receive a sibling proposal.
    A receipt contains the last generated bytes, never a human-edited baseline.
    """
    directory = Path(directory)
    receipt = read(directory) if receipt is None else receipt
    receipt = json.loads(json.dumps(receipt))
    result, kept = {}, []

    def public_path(name):
        path = check(directory, name)
        if public_directory is not None:
            path = Path(public_directory) / name
            if path.is_symlink() and os.readlink(path) != directory.name + '/' + name:
                raise ValueError('output_symlink')
        return path

    for name, content in outputs.items():
        path = public_path(name)
        old = contents(path) if path.exists() else None
        baseline = receipt['files'].get(name)
        edited = old is not None and (baseline is None or digest(old) != baseline['sha256'])
        if name == 'current-state.md':
            generated, placeholder = human_parts(content)
            outside, blocks = human_parts(old) if isinstance(old, str) else ('', [])
            content = generated.rstrip('\n') + '\n\n' + '\n\n'.join(blocks or placeholder)
            previous_outside = human_parts(baseline.get('text', ''))[0] if baseline else ''
            # Blank boundary lines separate blocks from generated prose, rather
            # than constituting human prose themselves.
            outside_edited = (outside.rstrip('\r\n') != previous_outside.rstrip('\r\n')
                              if isinstance(old, str) else old is not None)
            if outside_edited:
                previous = 'current-state.previous.md'
                backup = public_path(previous)
                if not backup.exists():
                    result[previous] = old
                    receipt['files'][previous] = record(old)
                    kept.append(str(backup))
            edited = False
        if name.endswith('.md') and edited:
            proposal = path.stem + '.proposed.md'
            # Never clobber an edited proposal either.
            candidate = public_path(proposal)
            prior = receipt['files'].get(proposal)
            index = 1
            while candidate.exists() and (prior is None or digest(contents(candidate)) != prior['sha256']):
                proposal = path.stem + '.proposed.{}.md'.format(index)
                candidate = public_path(proposal)
                prior = receipt['files'].get(proposal)
                index += 1
            result[name] = old
            result[proposal] = content
            receipt['files'][proposal] = record(content)
            kept.append(str(path))
        else:
            result[name] = content
            receipt['files'][name] = record(content)
    result[RECEIPT] = json.dumps(receipt, ensure_ascii=False, indent=2) + '\n'
    return result, kept


def write_text(directory, name, content):
    """Publish one summary/report through the same atomic generation mechanism."""
    from orcexe import mapping
    path = check(directory, name)
    baseline = read(directory)['files'].get(name)
    if baseline and path.exists() and contents(path) == content and digest(content) == baseline['sha256']:
        return []
    outputs, kept = prepare(directory, {name: content})
    if all((Path(directory) / key).exists() and contents(Path(directory) / key) == value
           for key, value in outputs.items()):
        return kept
    mapping.publish(Path(directory), outputs)
    return kept


def report(paths):
    if paths:
        import sys
        paths = list(dict.fromkeys(paths))
        previous = [p for p in paths if Path(p).name == 'current-state.previous.md']
        kept = [p for p in paths if p not in previous]
        if kept:
            print('human_edit_kept: ' + ', '.join(kept), file=sys.stderr)
        if previous:
            print('current_state_previous_saved: ' + ', '.join(previous), file=sys.stderr)
